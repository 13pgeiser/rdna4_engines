def cstr(s):
    out = '"'
    prev_hex = False
    for b in s.encode("utf-8"):
        c = chr(b)
        if c == '"':
            out += '\\"'; prev_hex = False
        elif c == "\\":
            out += "\\\\"; prev_hex = False
        elif 0x20 <= b < 0x7F:
            if prev_hex and c in "0123456789abcdefABCDEF":
                out += '" "'
            out += c; prev_hex = False
        else:
            out += "\\x%02x" % b; prev_hex = True
    return out + '"'


def grapheme_cases(path):
    """(codepoints, bitmask of the positions a cluster starts at, beyond the first)."""
    cases = []
    for line in open(path, encoding="utf-8"):
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        toks = line.split()
        cps, mask = [], 0
        for t in toks[1:-1]:
            if t in ("÷", "×"):
                if t == "÷":
                    mask |= 1 << len(cps)
                continue
            cps.append(int(t, 16))
        cases.append((cps, mask))
    return cases


