def path_regex(cfg: dict, crate_dirs: list[str]) -> str:
    dirs = [f"crates/{c}" for c in crate_dirs] + list(cfg["legacy"])
    return "^(?:" + "|".join(re.escape(f) + "$" for f in cfg["files"]) + "|" + \
           "|".join(re.escape(d) + "/" for d in dirs) + ")"


def build_filter(cfg, src, work):
    fr = load_filter_repo()
    branch = cfg["branch"]
    names, manifests, root_manifest = closure(src, cfg["roots"])
    run(["git", "init", "-q", f"--initial-branch={branch}", str(work)])
    run(["git", "-C", str(work), "fetch", "-q", "--no-tags", "--update-head-ok", "--no-recurse-submodules",
         "--upload-pack", "git -c uploadpack.allowAnySHA1InWant=true upload-pack",
         f"file://{src.repo}", f"{src.sha}:refs/heads/{branch}"])

    def commit_cb(commit, _meta):
        commit.message = MESSAGE.format(sha=commit.original_id.decode()).encode()

    argv = ["--force", "--refs", f"refs/heads/{branch}", "--prune-empty", "auto",
            "--path-regex", path_regex(cfg, names)]
    for old, new in cfg["legacy"].items():
        argv += ["--path-rename", f"{old}/:{new}/"]
    cwd = os.getcwd()
    os.chdir(work)
    try:
        fr.RepoFilter(fr.FilteringOptions.parse_args(argv), commit_callback=commit_cb).run()
    finally:
        os.chdir(cwd)

    shutil.rmtree(work / ".git" / "filter-repo", ignore_errors=True)
    for ref in git(work, "for-each-ref", "--format=%(refname)").decode().split():
        if ref != f"refs/heads/{branch}":
            git(work, "update-ref", "-d", ref)
    tip = git(work, "rev-parse", "--verify", f"refs/heads/{branch}").decode().strip()

    files: dict[str, bytes] = {
        "Cargo.toml": render_root_manifest(names, manifests, root_manifest, cfg["title"]).encode(),
        "README.md": render_readme(cfg, names, src.sha).encode(),
        ".gitignore": b"/target\n",
    }
    lock = src.show("Cargo.lock")
    pruned = prune_lock(lock.decode(), set(names)) if lock is not None else None
    if pruned is not None:
        files["Cargo.lock"] = pruned.encode()
    for path, data in files.items():
        check_generated(path, data.decode())

    def commit_top() -> None:
        env = dict(os.environ, GIT_INDEX_FILE=str(work / ".git" / "mirror-index"))
        git(work, "read-tree", tip, env=env)
        for path, data in sorted(files.items()):
            blob = git(work, "hash-object", "-w", "--stdin", input=data).decode().strip()
            git(work, "update-index", "--add", "--cacheinfo", f"100644,{blob},{path}", env=env)
        tree = git(work, "write-tree", env=env).decode().strip()
        (work / ".git" / "mirror-index").unlink()
        git(work, "update-ref", f"refs/heads/{branch}", commit_tree(work, src, tree, tip))
        git(work, "reset", "-q", "--hard", f"refs/heads/{branch}")

    commit_top()
    if "Cargo.lock" in files and settle_lock(work):
        settled = (work / "Cargo.lock").read_bytes()
        if settled != files["Cargo.lock"]:
            files["Cargo.lock"] = settled
            commit_top()
        shutil.rmtree(work / "target", ignore_errors=True)
    elif "Cargo.lock" in files:
        git(work, "checkout", "-q", "--", "Cargo.lock")

    for leftover in ("FETCH_HEAD", "ORIG_HEAD"):
        (work / ".git" / leftover).unlink(missing_ok=True)
    git(work, "reflog", "expire", "--expire=now", "--all")
    git(work, "gc", "-q", "--prune=now")
    return names


