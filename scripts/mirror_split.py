def render_readme(cfg: dict, names: list[str], src_sha: str) -> str:
    out = [
        f"# {cfg['title']}", "", cfg["blurb"], "",
        "## This repository is a mirror", "",
        f"The canonical development tree is **{CANONICAL}**. This repository is generated from it by",
        "`scripts/mirror-split.sh` and is rewritten on each update: open issues and pull requests, and",
        f"send contributions, at {CANONICAL} (see its `CONTRIBUTING.md`), not here.", "",
        "Author and commit dates and the commit topology of the kept paths are preserved. Commit",
        "messages are replaced by `Mirror source update` plus the canonical source commit hash.", "",
        f"Generated from canonical commit `{src_sha}`.", "",
        "## Contents", "", "Crates (each lives at `crates/<name>`):", "",
        *[f"- `{n}`" for n in names], "",
        "`Cargo.toml`, `Cargo.lock`, `README.md` and `.gitignore` at the root are generated for this",
        "mirror. Everything else is copied from the canonical tree unchanged.",
        "", "```", "cargo build --workspace", "cargo test --workspace", "```", "",
        "Tests that need a ROCm toolchain use `ROCM_PATH` (default `/opt/rocm`).", "",
    ]
    notes = [f"History of `{old}` is kept under `{new}`." for old, new in sorted(cfg["legacy"].items())]
    if notes:
        out += ["## History notes", "", *[f"- {n}" for n in notes], ""]
    out += ["## License", "",
            "Apache-2.0 (see `LICENSE`, `LICENSE-APACHE`, `LICENSE-MIT` and `NOTICE`). Individual files keep",
            "their SPDX headers.", ""]
    return "\n".join(out)


# ---------------------------------------------------------------------------
# git-filter-repo bootstrap
# ---------------------------------------------------------------------------
def load_filter_repo():
    try:
        import git_filter_repo as fr  # type: ignore
        return fr
    except ImportError:
        pass
    exe = os.environ.get("MIRROR_FILTER_REPO") or shutil.which("git-filter-repo")
    if not exe:
        die("git-filter-repo not found (pip install git-filter-repo==2.47.0, or set MIRROR_FILTER_REPO)")
    if os.environ.get("MIRROR_REEXEC"):
        die(f"{exe} is on PATH but its interpreter cannot import git_filter_repo")
    with open(exe, "rb") as fh:
        first = fh.readline().decode("utf-8", "replace")
    if not first.startswith("#!"):
        die(f"cannot determine the interpreter of {exe}")
    interp = shlex.split(first[2:].strip())
    os.environ["MIRROR_REEXEC"] = "1"
    os.execvp(interp[0], [*interp, os.path.abspath(__file__), *sys.argv[1:]])


def prepare_dest(dest: Path) -> Path:
    if dest.exists():
        die(f"{dest} exists; remove it first")
    dest.parent.mkdir(parents=True, exist_ok=True)
    return Path(tempfile.mkdtemp(prefix=f".{dest.name}.tmp-", dir=dest.parent))


def commit_tree(work: Path, src: Source, tree: str, parent: str) -> str:
    env = dict(os.environ)
    date = src.commit_date()
    env.update({"GIT_AUTHOR_NAME": MIRROR_IDENT[0], "GIT_AUTHOR_EMAIL": MIRROR_IDENT[1],
                "GIT_COMMITTER_NAME": MIRROR_IDENT[0], "GIT_COMMITTER_EMAIL": MIRROR_IDENT[1],
                "GIT_AUTHOR_DATE": date, "GIT_COMMITTER_DATE": date})
    return git(work, "commit-tree", tree, "-p", parent, input=MESSAGE.format(sha=src.sha).encode(),
               env=env).decode().strip()


