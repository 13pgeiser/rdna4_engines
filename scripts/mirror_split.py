DEP_TABLES = ("dependencies", "dev-dependencies", "build-dependencies")


def dep_tables(manifest: dict):
    for table in DEP_TABLES:
        yield manifest.get(table, {})
    for cfg in manifest.get("target", {}).values():
        for table in DEP_TABLES:
            yield cfg.get(table, {})


def closure(src: Source, roots: list[str]):
    """Path-dependency closure of `roots` (crate names under crates/)."""
    root_manifest = src.toml("Cargo.toml") or die("source commit has no root Cargo.toml")
    manifests: dict[str, dict] = {}
    stack = list(roots)
    while stack:
        name = stack.pop()
        if name in manifests:
            continue
        m = src.toml(f"crates/{name}/Cargo.toml")
        if m is None:
            die(f"crates/{name}/Cargo.toml is missing at {src.sha[:12]} (is the rename committed?)")
        manifests[name] = m
        for table in dep_tables(m):
            for dep, spec in table.items():
                if not isinstance(spec, dict) or "path" not in spec:
                    continue
                target = posixpath.normpath(posixpath.join(f"crates/{name}", spec["path"]))
                if not target.startswith("crates/") or target.count("/") != 1:
                    die(f"crates/{name}: path dependency `{dep}` -> `{target}` is outside crates/<name>")
                stack.append(target.split("/", 1)[1])
    return sorted(manifests), manifests, root_manifest


def inherited(manifests: dict[str, dict], names: list[str], ws: dict):
    """(workspace.package keys inherited, workspace dependency keys used)."""
    pkg: set[str] = set()
    deps: set[str] = set()
    for name in names:
        m = manifests[name]
        for key, val in m.get("package", {}).items():
            if isinstance(val, dict) and val.get("workspace"):
                pkg.add(key)
        for table in dep_tables(m):
            for dep, spec in table.items():
                if isinstance(spec, dict) and spec.get("workspace"):
                    deps.add(dep)
        if m.get("lints", {}).get("workspace"):
            die(f"{name} inherits [workspace.lints]; not supported")
    for key in pkg:
        if key not in ws.get("package", {}):
            die(f"closure inherits workspace.package.{key} which the source workspace does not define")
    for dep in deps:
        spec = ws.get("dependencies", {}).get(dep)
        if spec is None:
            die(f"closure uses workspace dependency `{dep}` which the source workspace does not define")
        if isinstance(spec, dict) and "path" in spec:
            die(f"workspace dependency `{dep}` is a path dependency; not supported")
    return pkg, deps


# ---------------------------------------------------------------------------
# TOML emission and textual editing (tomllib is read-only; edits keep comments)
# ---------------------------------------------------------------------------
def toml_key(key: str) -> str:
    return key if re.fullmatch(r"[A-Za-z0-9_-]+", key) else json.dumps(key)


def toml_val(v) -> str:
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(v)
    if isinstance(v, str):
        return json.dumps(v)
    if isinstance(v, list):
        return "[" + ", ".join(toml_val(x) for x in v) + "]"
    if isinstance(v, dict):
        return "{ " + ", ".join(f"{toml_key(k)} = {toml_val(x)}" for k, x in v.items()) + " }" if v else "{}"
    raise TypeError(f"unsupported TOML value {v!r}")


HEADER_RX = re.compile(r"^\[\[?\s*([^\]\n]+?)\s*\]\]?\s*(#.*)?$")


def section_span(lines: list[str], header: str) -> tuple[int, int] | None:
    """(header line index, index one past the section's last non-blank line)."""
    start = None
    for i, line in enumerate(lines):
        m = HEADER_RX.match(line)
        if m:
            if start is not None:
                end = i
                break
            if re.sub(r"\s+", "", m.group(1)) == header:
                start = i
    else:
        end = len(lines)
    if start is None:
        return None
    while end > start + 1 and not lines[end - 1].strip():
        end -= 1
    return start, end


def add_to_section(text: str, header: str, new_lines: list[str]) -> str:
    if not new_lines:
        return text
    lines = text.split("\n")
    span = section_span(lines, header)
    if span is None:
        if lines and lines[-1] == "":
            lines.pop()
        lines += ["", f"[{header}]", *new_lines, ""]
    else:
        lines[span[1]:span[1]] = new_lines
    return "\n".join(lines)


def array_bounds(text: str, start: int) -> tuple[int, int | None]:
    """`start` indexes the '[' of an array. Returns (index of closing ']', index of last significant char)."""
    depth, i, last, in_str = 0, start, None, None
    while i < len(text):
        c = text[i]
        if in_str:
            if c == "\\" and in_str == '"':
                i += 1
            elif c == in_str:
                in_str = None
            last = i
        elif c in "\"'":
            in_str, last = c, i
        elif c == "#":
            while i < len(text) and text[i] != "\n":
                i += 1
            continue
        elif c == "[":
            depth += 1
            last = i if depth > 1 else last
        elif c == "]":
            depth -= 1
            if depth == 0:
                return i, last
            last = i
        elif not c.isspace():
            last = i
        i += 1
    die("unterminated members array in the master root Cargo.toml")


def add_members(text: str, new: list[str]) -> str:
    if not new:
        return text
    lines = text.split("\n")
    span = section_span(lines, "workspace")
    if span is None:
        die("master root Cargo.toml has no [workspace] table")
    offset = sum(len(l) + 1 for l in lines[:span[0]])
    body = text[offset:]
    m = re.search(r"(?m)^[ \t]*members[ \t]*=[ \t]*\[", body)
    if not m:
        die("master root Cargo.toml: [workspace] has no `members = [...]` array")
    open_pos = offset + m.end() - 1
    close, last = array_bounds(text, open_pos)
    line_start = text.rfind("\n", 0, close) + 1
    entries = [f'"{p}"' for p in new]
    if text[line_start:close].strip() == "" and "\n" in text[open_pos:close]:
        indent = re.match(r"[ \t]*", text[text.index("\n", open_pos) + 1:]).group(0) or "    "
        block = "".join(f"{indent}{e},\n" for e in entries)
        out = text[:line_start] + block + text[line_start:]
        if last is not None and last > open_pos and text[last] != ",":
            out = out[:last + 1] + "," + out[last + 1:]
        return out
    sep = "" if (last is None or last <= open_pos or text[last] == ",") else ","
    inner = (" " if last is not None and last > open_pos else "")
    return text[:last + 1 if last and last > open_pos else open_pos + 1] + sep + inner + ", ".join(entries) + \
        text[(last + 1 if last and last > open_pos else open_pos + 1):]


def transform_manifest(text: str, ws_pkg_src: dict, ws_pkg_master: dict, rewrites: dict[str, str]) -> tuple[str, list[str]]:
    """Make an overlaid crate manifest resolve under the master workspace."""
    out, section, notes = [], "", []
    for line in text.split("\n"):
        m = HEADER_RX.match(line)
        if m:
            section = re.sub(r"\s+", "", m.group(1))
        if section == "package":
            m2 = re.match(r"^([A-Za-z0-9_-]+)(?:\.workspace\s*=\s*true|\s*=\s*\{\s*workspace\s*=\s*true\s*\})\s*(#.*)?$", line)
            if m2:
                key = m2.group(1)
                if key != "version" and key in ws_pkg_master and ws_pkg_master[key] != ws_pkg_src[key]:
                    line = f"{toml_key(key)} = {toml_val(ws_pkg_src[key])}"
                    notes.append(f"{key} = {ws_pkg_src[key]!r} (master workspace has {ws_pkg_master[key]!r})")
        for old, new in rewrites.items():
            line = re.sub(rf'(path\s*=\s*"){re.escape(old)}(")', rf"\g<1>{new}\g<2>", line)
        out.append(line)
    return "\n".join(out), notes


def render_root_manifest(names, manifests, root_manifest, title) -> str:
    ws = root_manifest.get("workspace", {})
    pkg, deps = inherited(manifests, names, ws)
    lines = [
        "# SPDX-License-Identifier: Apache-2.0",
        f"# Generated by scripts/mirror-split.sh in the canonical hipfire repository for the {title}",
        "# mirror: the inherited workspace package keys and only the workspace dependencies",
        f"# the crates below actually use. Edit {CANONICAL} instead.",
        "[workspace]", 'resolver = "2"', "members = [", *[f'    "crates/{n}",' for n in names], "]", "",
        "[workspace.package]",
        *[f"{toml_key(k)} = {toml_val(v)}" for k, v in ws["package"].items() if k in pkg],
        "", "[workspace.dependencies]",
        *[f"{toml_key(k)} = {toml_val(v)}" for k, v in ws["dependencies"].items() if k in deps],
    ]
    return "\n".join(lines) + "\n"


def prune_lock(text: str, names: set[str]) -> str | None:
    blocks = re.split(r"\n(?=\[\[package\]\]\n)", text)
    header, pkgs = blocks[0], blocks[1:]
    if not pkgs:
        return None
    parsed = [tomllib.loads(b)["package"][0] for b in pkgs]
    by_name: dict[str, list[int]] = {}
    for i, p in enumerate(parsed):
        by_name.setdefault(p["name"], []).append(i)

    def resolve(dep: str) -> int | None:
        parts = dep.split(" ", 2)
        cands = by_name.get(parts[0], [])
        if len(parts) > 1:
            cands = [i for i in cands if parsed[i]["version"] == parts[1]]
        if len(parts) > 2:
            cands = [i for i in cands if parsed[i].get("source") == parts[2].strip("()")]
        return cands[0] if len(cands) == 1 else None

    keep: set[int] = set()
    stack = [i for i, p in enumerate(parsed) if p["name"] in names and "source" not in p]
    while stack:
        i = stack.pop()
        if i in keep:
            continue
        keep.add(i)
        for dep in parsed[i].get("dependencies", []):
            j = resolve(dep)
            if j is None:
                return None
            stack.append(j)
    return "\n\n".join([header.rstrip("\n")] + [pkgs[i].strip("\n") for i in sorted(keep)]) + "\n"


def settle_lock(work: Path) -> bool:
    """Let cargo reconcile Cargo.lock (never builds). Returns True if cargo ran successfully."""
    if not shutil.which("cargo"):
        return False
    for extra in (["--offline"], []):
        if run(["cargo", "metadata", "--format-version", "1", *extra], cwd=work, check=False).returncode == 0:
            return True
    print("mirror-split: warning: `cargo metadata` failed; Cargo.lock left as generated "
          "(the first cargo command will settle it)", file=sys.stderr)
    return False


