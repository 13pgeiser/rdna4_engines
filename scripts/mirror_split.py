def main(argv: list[str]) -> int:
    if len(argv) < 1 or len(argv) > 2 or argv[0] not in MIRRORS:
        die(f"usage: scripts/mirror-split.sh <{'|'.join(MIRRORS)}> [destination]")
    name = argv[0]
    cfg = MIRRORS[name]
    repo_root = Path(__file__).resolve().parent.parent
    dest = Path(os.path.abspath(Path(argv[1]) if len(argv) == 2 else repo_root / "mirror-preview" / name))
    for var in ("GIT_DIR", "GIT_WORK_TREE", "GIT_INDEX_FILE"):
        os.environ.pop(var, None)
    os.environ.update({"LC_ALL": "C", "GIT_TERMINAL_PROMPT": "0"})
    if cfg["kind"] == "filter":  # local-only: isolate from user git config
        os.environ.update({"GIT_CONFIG_GLOBAL": os.devnull, "GIT_CONFIG_NOSYSTEM": "1"})
        load_filter_repo()

    src = Source(repo_root, os.environ.get("MIRROR_SOURCE_REV", "HEAD"))
    work = prepare_dest(dest)
    try:
        print(f"mirror-split: {name} from {src.sha}")
        names = build_filter(cfg, src, work) if cfg["kind"] == "filter" else build_overlay(cfg, src, work)
        os.rename(work, dest)
    except BaseException:
        shutil.rmtree(work, ignore_errors=True)
        raise
    print(f"mirror-split: {name} written to {dest} (branch {cfg['branch']}); nothing pushed")
    print(f"  crates: {', '.join(names)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
