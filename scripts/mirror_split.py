"""Sync hipfire sub-projects to their standalone public repositories.

    scripts/mirror-split.sh <peacemaker|redline> [destination]

Never pushes; the caller does. The source checkout is only read. The destination
(default mirror-preview/<name> under the source checkout) must not exist.
Environment: MIRROR_SOURCE_REV (source commit-ish, default HEAD),
MIRROR_REDLINE_REMOTE (redline overlay base; default
https://github.com/warpfront/redline.git, no credentials in the URL),
MIRROR_FILTER_REPO (path of git-filter-repo 2.47.0 if it is not on PATH).

peacemaker -- history-preserving filter (branch `main`)
  Fetches the full history of the source commit into a throw-away repository over
  file:// (the equivalent of `git clone --no-local --single-branch`) and rewrites
  it with git-filter-repo:
    * keeps only the path-dependency closure of peacemaker-ir/-lift/-author/-npu
      (derived from the committed manifests), the license files / NOTICE and the
      listed fixtures; the historical crates/pm-npu is path-renamed to
      crates/peacemaker-npu so the rename keeps its history. The source root
      Cargo.toml / README history is NOT kept;
    * kept blobs are byte-for-byte copies of the source blobs;
    * every commit gets the neutral message `Mirror source update` plus the
      canonical source commit hash; author/committer dates and topology are
      preserved;
    * one top commit (dated like the source commit, stable identity) adds the
      generated root files: Cargo.toml (inherited workspace.package keys and only
      the workspace dependencies the closure uses), a Cargo.lock pruned from the
      source lock and settled with `cargo metadata`, README.md and .gitignore.

redline -- overlay onto the existing public master (branch `master`)
  Clones MIRROR_REDLINE_REMOTE with its complete history and adds ONE commit on
  master:
    * canonical files of crates/redline, crates/redline-rocr and
      crates/redline-dispatch overwrite the same paths; nothing is ever deleted
      and master-only files are untouched;
    * the rest of their path-dependency closure (hipfire-config only; anything
      else is refused) is copied to vendor/<name>, and the path dependencies of
      the copied roots are rewritten from ../<name> to ../../vendor/<name>;
    * the master root Cargo.toml is edited textually: only missing workspace
      members, workspace.dependencies and workspace.package keys are added;
      existing members, excludes, metadata and values are preserved. Package keys
      that the source crates inherit but master defines differently (edition,
      license, ...) are written explicitly into the copied manifests, so the
      copied crates keep compiling as in hipfire; `version` follows master;
    * the fixtures the vendored crates' tests read (docs/configs/*.toml) are
      added only if absent; Cargo.lock is settled with cargo if it is tracked.
  Commit message and identity are as for peacemaker; the commit is dated like the
  source commit. If nothing changed, no commit is made.

Text generated by this script (README, root manifests, lockfile) is checked for
private paths and machine names and the run fails if any appear. Copied source
content is not inspected or altered.
"""
