# redline: overlay onto the public master
# ---------------------------------------------------------------------------
def build_overlay(cfg, src, work):
    branch, remote = cfg["branch"], os.environ.get("MIRROR_REDLINE_REMOTE", cfg["remote"])
    _REDACT.append(remote)
    roots, vdir = cfg["roots"], cfg["vendor_dir"]
    names, manifests, root_manifest = closure(src, roots)
    vendor = [n for n in names if n not in roots]
    extra = [n for n in vendor if n not in cfg["vendor_allow"]]
    if extra:
        die(f"the closure of {', '.join(roots)} reaches {', '.join(extra)} beyond "
            f"{', '.join(cfg['vendor_allow'])}; refusing to copy it (decide first)")
    dest_dir = {n: (f"crates/{n}" if n in roots else f"{vdir}/{n}") for n in names}

    run(["git", "clone", "-q", "--no-local", "--single-branch", "--branch", branch, remote, str(work)])
    tip = git(work, "rev-parse", "--verify", "HEAD").decode().strip()
    if git(work, "status", "--porcelain").strip():
        die("fresh clone is not clean")
    master_text = (work / "Cargo.toml").read_text() if (work / "Cargo.toml").exists() else die(
        f"{branch} has no root Cargo.toml")
    master = tomllib.loads(master_text)
    mws = master.get("workspace") or die(f"{branch} root Cargo.toml has no [workspace]")
    src_ws = root_manifest["workspace"]
    pkg_keys, dep_keys = inherited(manifests, names, src_ws)

    # --- copy files (never delete) ---
    rewrites = {f"../{n}": f"../../{vdir}/{n}" for n in vendor}
    staged: list[str] = []
    notes: list[str] = []
    overwritten = created = 0
    todo: list[tuple[str, str, str]] = []  # (mode, oid, dest path)
    for name in names:
        entries = src.tree(f"crates/{name}")
        if not entries:
            die(f"crates/{name} has no files at {src.sha[:12]}")
        for mode, oid, path in entries:
            todo.append((mode, oid, dest_dir[name] + path[len(f"crates/{name}"):]))
    fixtures = []
    for fx in cfg["fixtures"]:
        if (work / fx).exists():
            notes.append(f"fixture {fx}: kept master's copy")
        else:
            fixtures += [(m, o, fx) for m, o, p in src.tree(fx)]
    todo += fixtures
    blobs = src.blobs(sorted({oid for _, oid, _ in todo}))
    for mode, oid, dpath in todo:
        data = blobs[oid]
        target = work / dpath
        if mode == "120000":
            if target.is_symlink() or target.is_file():
                target.unlink()
            elif target.exists():
                die(f"{dpath}: master has a directory where the source has a symlink")
            target.parent.mkdir(parents=True, exist_ok=True)
            os.symlink(data.decode(), target)
        else:
            if target.exists() and not target.is_file() or target.is_symlink():
                die(f"{dpath}: master has a non-regular file where the source has a file")
            existed = target.exists()
            for parent in target.parents:
                if parent == work:
                    break
                if parent.exists() and not parent.is_dir():
                    die(f"{parent.relative_to(work)}: master has a file where the source has a directory")
            if posixpath.basename(dpath) == "Cargo.toml" and dpath in {f"{d}/Cargo.toml" for d in dest_dir.values()}:
                crate = next(n for n, d in dest_dir.items() if d == posixpath.dirname(dpath))
                text, why = transform_manifest(data.decode(), src_ws.get("package", {}),
                                               mws.get("package", {}), rewrites if crate in roots else {})
                data = text.encode()
                notes += [f"{dpath}: {w}" for w in why]
            target.parent.mkdir(parents=True, exist_ok=True)
            if not (existed and target.read_bytes() == data):
                target.write_bytes(data)
            target.chmod(0o755 if mode == "100755" else 0o644)
            overwritten += existed
            created += not existed
        staged.append(dpath)

    # --- merge the root manifest (additions only) ---
    members_have = mws.get("members", [])
    excluded = mws.get("exclude", [])
    new_members = []
    for n in names:
        d = dest_dir[n]
        if any(fnmatch.fnmatchcase(d, pat) for pat in excluded):
            die(f"{d} is excluded from the master workspace")
        if not any(fnmatch.fnmatchcase(d, pat) for pat in members_have):
            new_members.append(d)
    mws_pkg, mws_deps = mws.get("package", {}), mws.get("dependencies", {})
    new_pkg = [f"{toml_key(k)} = {toml_val(src_ws['package'][k])}" for k in src_ws["package"]
               if k in pkg_keys and k not in mws_pkg]
    new_deps = [f"{toml_key(k)} = {toml_val(v)}" for k, v in src_ws["dependencies"].items()
                if k in dep_keys and k not in mws_deps]
    for k in sorted(dep_keys & set(mws_deps)):
        if mws_deps[k] != src_ws["dependencies"][k]:
            notes.append(f"workspace dependency {k}: master pins {toml_val(mws_deps[k])}, hipfire uses "
                         f"{toml_val(src_ws['dependencies'][k])}; master's kept")
    text = add_members(master_text, new_members)
    text = add_to_section(text, "workspace.package", new_pkg)
    text = add_to_section(text, "workspace.dependencies", new_deps)
    for snippet in new_members + new_pkg + new_deps:
        check_generated("root manifest addition", snippet)
    merged = tomllib.loads(text)
    got = merged["workspace"]
    for d in new_members:
        assert any(fnmatch.fnmatchcase(d, p) for p in got["members"]), d
    for k in dep_keys:
        assert k in got["dependencies"], k
    if text != master_text:
        (work / "Cargo.toml").write_text(text)
        staged.append("Cargo.toml")

    # --- commit ---
    def stage(paths: list[str]) -> None:
        git(work, "add", "-f", "--pathspec-from-file=-", "--pathspec-file-nul",
            input=b"\0".join(p.encode() for p in paths) + b"\0")

    stage(staged)
    if (work / "Cargo.lock").exists() and git(work, "ls-files", "Cargo.lock").strip() and settle_lock(work):
        stage(["Cargo.lock"])
    tree = git(work, "write-tree").decode().strip()
    if tree == git(work, "rev-parse", "HEAD^{tree}").decode().strip():
        print("mirror-split: master already contains this source state; no commit created")
    else:
        commit = commit_tree(work, src, tree, tip)
        git(work, "update-ref", "-m", "mirror overlay", "refs/heads/" + branch, commit, tip)
        git(work, "reset", "-q", "--hard", commit)
    if (work / "target").is_dir() and not git(work, "ls-files", "target").strip():
        shutil.rmtree(work / "target", ignore_errors=True)

    print(f"  overlay: {created} file(s) added, {overwritten} overwritten, 0 deleted (base master {tip[:12]})")
    for n in new_members:
        why = "mirrored crate" if n.startswith("crates/") else "closure dependency of redline-rocr/redline-dispatch"
        print(f"  workspace member added: {n} ({why})")
    for line in new_pkg:
        print(f"  workspace.package added: {line} (inherited by the mirrored crates)")
    for line in new_deps:
        print(f"  workspace.dependencies added: {line} (used by the mirrored crates)")
    for note in notes:
        print(f"  note: {note}")
    return names


